def _goal_section() -> str:
    """指示の「目的ごとの手順」の節 (3 つの目的の見出しと手順の文) を返す。"""
    parts = [
        (
            "\n# 目的ごとの手順\n\n"
            "user メッセージの目的の節にある目的の手順に従います。3 つの目的の手順は次のとおりです。\n"
        )
    ]
    for goal, text in _GOAL_TEXTS.items():
        parts.append(f"\n## {goal.value} ({_GOAL_TITLES[goal]})\n\n{text}\n")
    return "".join(parts)


